const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH}:{})});
  const page = await browser.newPage({viewport:{width:1440,height:1080}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:8000');
  await page.getByText('Service ready',{exact:true}).waitFor();
  await page.waitForFunction(() => document.getElementById('document-count').textContent === '16');
  await page.screenshot({path:'docs/workspace.png',fullPage:true});
  await page.locator('[data-question]').first().click();
  await page.getByText('Evidence found',{exact:true}).waitFor();
  assert.match(await page.locator('.answer-text').textContent(), /VPN/);
  await page.getByRole('button',{name:'Yes',exact:true}).click();
  await page.getByText('Feedback recorded. Thank you.').waitFor();
  await page.screenshot({path:'docs/answer.png',fullPage:true});
  await page.waitForFunction(() => !document.getElementById('ask').disabled);
  await page.locator('[data-question]').nth(2).click();
  await page.getByText('Escalate · evidence gap',{exact:true}).waitFor();
  await page.locator('[data-view="knowledge"]').click();
  assert.equal(await page.locator('.document').count(),16);
  await page.locator('[data-view="activity"]').click();
  assert.match(await page.locator('#stats').textContent(), /requests/);
  await page.locator('[data-view="assistant"]').click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'docs/mobile.png',fullPage:true});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('Browser smoke checks passed: answer, escalation, feedback, corpus, activity, mobile overflow.');
})().catch(e=>{console.error(e);process.exit(1)});
